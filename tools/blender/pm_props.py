"""pm_props.py — PetaByte Madness' OBJ-sourced models.

    blender --background --factory-startup -noaudio --python pm_props.py \
        -- --model island --out build/island.gltf

One script with a MODELS table, the same shape goblin.py and models.py use,
because every one of these is the same three steps: read an OBJ, colour it,
decimate if it is too heavy for the console. The parsing lives in objkit.py
(no `bpy`, testable with a bare python3); this file is only the Blender half.

── Scale: 1 Blender unit = 1 metre, always ────────────────────────────────
Every model here is scaled to its real size in metres, taken from the drop's
own specs — docs/LOACH_spec.md gives the sub as 2.86 m long, the guards are
people, the centaur came out of its generator in centimetres. Normalising on
metres means the flake's `baseScale` is a single meaningful dial (world units
per metre) instead of a per-model fudge factor, and it means a wrong number is
visible as "that submarine is the size of a car" rather than as a silent
mismatch between two models that were never in the same room until now.

── The submarine is deliberately oversized ────────────────────────────────
LOACH_spec.md describes a one-person boat: 2.86 m, "crew 1, seated, knees up".
The centaur is a 2.5 m wide-and-low quadruped and does not fit in that by any
reading. The intro needs him to climb out of it, so the sub is scaled up until
he does. Chosen over modelling a variant hull: it costs one number, and the
spec's proportions — the tank hull, the dished ends, the two mismatched
battery pods — all survive being bigger.
"""

import math
import os
import sys

import bpy

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import m64lib as m  # noqa: E402
import objkit  # noqa: E402

# Paths below are relative to the assets directory, which arrives as
# `--assets <dir>`. It is a DIRECTORY rather than one file per model because
# loach.obj needs its loach.mtl sibling to resolve, and a Nix store path for a
# single file has no siblings. Defaults to the in-repo location so the script
# still runs by hand from the repo root.
DEFAULT_ASSETS = "PetaByte-Madness/assets"


def _island_colors(verts, faces, groups):
    """Colour the island by height and slope.

    island_n64.obj carries no vertex colours — its generator's palette did not
    survive the OBJ export (3 floats per `v`, not 6), and regenerating needs
    numpy + scipy + matplotlib, which is a heavy dependency to add to a
    hermetic build for data we can derive from the geometry we already have.

    Height and slope give the banded look an N64 island wants anyway: the
    palette is deliberately few, flat and separated in VALUE, so it still
    reads once the veil collapses hue (docs/VEIL_DESIGN.md §4).
    """
    lo = min(v[2] for v in verts)
    hi = max(v[2] for v in verts)
    span = max(hi - lo, 1e-6)

    WET_SAND = m.srgb(132, 116, 88)
    SAND     = m.srgb(196, 178, 138)
    SCRUB    = m.srgb(86, 104, 62)
    GRASS    = m.srgb(64, 84, 48)
    ROCK     = m.srgb(112, 108, 100)
    HIGH     = m.srgb(74, 72, 68)

    colors = [SAND] * len(verts)
    for face, group in zip(faces, groups):
        a, b, c = (verts[i] for i in face)
        u = [b[i] - a[i] for i in range(3)]
        w = [c[i] - a[i] for i in range(3)]
        n = (u[1] * w[2] - u[2] * w[1],
             u[2] * w[0] - u[0] * w[2],
             u[0] * w[1] - u[1] * w[0])
        length = math.sqrt(sum(v * v for v in n)) or 1.0
        # Flat ground has a normal pointing straight up (+Z after the axis
        # change); a cliff face's is near horizontal.
        flatness = abs(n[2] / length)

        for i in face:
            h = (verts[i][2] - lo) / span
            if group == "cliffs" or flatness < 0.55:
                colors[i] = ROCK if h < 0.55 else HIGH
            elif h < 0.015:
                colors[i] = WET_SAND
            elif h < 0.07:
                colors[i] = SAND
            elif h < 0.45:
                colors[i] = SCRUB
            else:
                colors[i] = GRASS
    return colors


