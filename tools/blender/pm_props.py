def _source(spec):
    return os.path.join(m.arg("--assets", DEFAULT_ASSETS), spec["obj"])


def _load(spec):
    path = _source(spec)
    if not os.path.exists(path):
        raise SystemExit(
            "pm_props: no such source '%s'.\n"
            "  Pass --assets <dir> pointing at PetaByte-Madness/assets, or run\n"
            "  from the repo root where the default path resolves." % path)
    if spec.get("kind") == "gltf":
        return objkit.load_gltf(path)
    return objkit.load_obj(path)


def _loose_groups(obj, min_tris):
    """Connected components -> named groups, tiny fragments merged.

    Names carry intent, not just an index: the tall components are palms and
    the short ones shrubs, so the game asks for "palm_00" rather than knowing
    that component 3 happens to be a tree.
    """
    parts = objkit.loose_parts(obj["faces"])
    groups = {}
    scatter = []
    palms = shrubs = 0
    for faces in parts:
        if len(faces) < min_tris:
            scatter.extend(faces)
            continue
        height = max(obj["verts"][i][1] for f in faces for i in f) - \
            min(obj["verts"][i][1] for f in faces for i in f)
        if height >= 2.0:
            groups["palm_%02d" % palms] = faces
            palms += 1
        else:
            groups["shrub_%02d" % shrubs] = faces
            shrubs += 1
    if scatter:
        groups["scatter"] = scatter
    return groups


def build(spec):
    obj = _load(spec)

    # Must run before anything reads verts/colors: it appends to both.
    cloned = objkit.split_double_sided(obj)
    if cloned:
        print("  cloned %d double-sided face(s) so Blender keeps both windings"
              % cloned)

    scale = spec["scale"]
    verts = [tuple(c * scale for c in objkit.yup_to_zup(v))
             for v in obj["verts"]]

    if spec["color"] == "island":
        colors = _island_colors(verts, obj["faces"], obj["face_group"])
    elif spec["color"] == "vertex":
        if not obj["colors"]:
            raise SystemExit(f"pm_props: {spec['obj']} has no vertex colours")
        colors = [m.srgb(*(int(round(v * 255)) for v in c))
                  for c in obj["colors"]]
    else:  # "mtl" — bake the material's diffuse into the vertices
        mtl = objkit.load_mtl(os.path.splitext(_source(spec))[0] + ".mtl")
        colors = [m.srgb(255, 255, 255)] * len(verts)
        for face, material in zip(obj["faces"], obj["face_material"]):
            kd = mtl.get(material)
            if kd is None:
                continue
            rgb = m.srgb(*(int(round(v * 255)) for v in kd))
            for i in face:
                colors[i] = rgb

    if spec["split"] == "loose":
        groups = _loose_groups(obj, spec.get("loose_min_tris", 8))
    else:
        groups = objkit.group_faces(obj, by=spec["split"])
    total = 0
    for name, faces in sorted(groups.items()):
        used = sorted({i for f in faces for i in f})
        remap = {old: new for new, old in enumerate(used)}
        m.make_material(name)
        mesh = m.make_mesh(
            name,
            [verts[i] for i in used],
            [tuple(remap[i] for i in f) for f in faces],
            name,
            colors=[colors[i] for i in used],
            smooth=False,
        )
        if spec["decimate"]:
            mod = mesh.modifiers.new(name="Decimate", type='DECIMATE')
            mod.ratio = spec["decimate"]
            # Applied here rather than left to export_apply, so the triangle
            # count this script PRINTS is the count that ships. A budget you
            # only learn after the fact is not a budget.
            bpy.context.view_layer.objects.active = mesh
            bpy.ops.object.modifier_apply(modifier=mod.name)
        total += len(mesh.data.polygons)

    return total


def main():
    name = m.arg("--model")
    if name not in MODELS:
        raise SystemExit("pm_props.py: no model '%s' (have: %s)"
                         % (name, ", ".join(sorted(MODELS))))
    spec = MODELS[name]

    m.reset_scene()
    tris = build(spec)

    src = _load(spec)
    print("── %s: %d tris in, %d out%s ──"
          % (name, len(src["faces"]), tris,
             "" if not spec["decimate"]
             else " (decimate %.2f)" % spec["decimate"]))

    m.export_gltf(m.arg("--out"))


main()
